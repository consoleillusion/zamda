// The order of the binary format's type ids (docs/IR-BINARY.md).
const TYPES: readonly TypeName[] = [
  'bool', 'int8', 'int16', 'int32', 'int64', 'uint8', 'uint16', 'uint32', 'uint64',
  'float32', 'float64', 'utf8', 'dictionary', 'date32', 'timestamp',
];

function rustType(name: TypeName): string {
  // Purpose: the Rust enum variant for a type name
  return name.charAt(0).toUpperCase() + name.slice(1);
}

export function signaturesRs(): string {
  // Purpose: the registry's type rules as Rust source: every argument tuple of up to three types a function accepts
  const lines = [
    '// Generated by `bun run gen:engine` from src/registry.ts. Do not edit.',
    '// For each function: whether it is an aggregate, and every tuple of argument types',
    '// (up to three arguments) it accepts, with the result type it gives.',
    '',
    'use crate::types::Type;',
    'use crate::types::Type::*;',
    '',
    'pub struct Function {',
    '    pub name: &\'static str,',
    '    pub aggregate: bool,',
    '    pub signatures: &\'static [(&\'static [Type], Type)],',
    '}',
    '',
  ];
  const entries: string[] = [];
  for (const def of REGISTRY.values()) {
    const sigs: string[] = [];
    const tuples: TypeName[][] = [[]];
    for (let arity = 0; arity <= 3; arity++) {
      const next: TypeName[][] = [];
      for (const tuple of tuples.filter(x => x.length === arity)) {
        try {
          const result = def.returns(tuple.map(n => ({ name: n }) as DataType));
          sigs.push(`(&[${tuple.map(rustType).join(', ')}], ${rustType(result.name)})`);
        } catch {
          // not accepted
        }
        for (const n of TYPES) next.push([...tuple, n]);
      }
      tuples.push(...next);
    }
    // Arity four must be rejected by every function; the table has no arity beyond three.
    for (const a of TYPES) for (const b of TYPES) {
      try {
        def.returns([a, b, a, b].map(n => ({ name: n }) as DataType));
        throw new Error(`${def.name} accepts four arguments: extend the generator`);
      } catch (error) {
        if (error instanceof Error && error.message.includes('extend the generator')) throw error;
      }
    }
    entries.push(`    Function { name: "${def.name}", aggregate: ${def.kind === 'aggregate'}, signatures: &[${sigs.join(', ')}] },`);
  }
  lines.push(`pub static FUNCTIONS: [Function; ${entries.length}] = [`, ...entries, '];', '');
  const matrix = TYPES.map(from => `    [${TYPES.map(to => String(canCast({ name: from } as DataType, { name: to } as DataType))).join(', ')}],`);
  lines.push('// CAN_CAST[from][to], types in the binary format\'s id order.', 'pub static CAN_CAST: [[bool; 15]; 15] = [', ...matrix, '];', '');
  return lines.join('\n');
}

// ---- the corpus ----

const People = schema({ name: t.utf8, age: t.int32, big: t.int64, score: t.float64, city: t.dictionary, born: t.date32, seen: t.timestamp, ok: t.bool });
const Small = schema({ a: t.uint8, b: t.uint8 });

function basePlans(): { name: string; plan: IrPlan }[] {
  // Purpose: valid plans that between them use every node kind, expression kind and a spread of functions
  const out: { name: string; plan: IrPlan }[] = [];
  for (const [id, plan] of Object.entries(compilePlans())) out.push({ name: `dashboard-${id}`, plan: plan.ir });
  const add = (name: string, plan: { ir: IrPlan }): void => void out.push({ name, plan: plan.ir });
  add('filter-in-or-not', pipe(People).filter(c => c.age.gt(30).and(c.city.isIn(['Auckland', 'Sydney'])).or(c.ok.not())).compile());
  add('select-arith', pipe(People).select(c => ({ a: c.age.cast(t.float64), n: c.name.upper(), d: c.big.add(1n), m: c.age.mod(7) })).compile());
  add('group-aggs', pipe(People).groupBy(c => ({ city: c.city })).agg(c => ({ n: count(), top: c.score.max(), who: c.name.min(), u: c.age.countDistinct(), s: c.age.sum(), v: c.score.avg() })).compile());
  add('sort-limit', pipe(People).sort(c => [c.age.desc(), c.score.asc().nullsFirst(), c.name.asc()]).limit(25).compile());
  add('strings-dates', pipe(People).filter(c => c.name.lower().contains('a').and(c.name.startsWith('x').not())).select(c => ({ y: c.born.extract('year'), t: c.seen.dateTrunc('day') })).compile());
  add('small', pipe(Small).filter(c => c.a.between(1, 9)).select(c => ({ s: c.a.add(c.b) })).compile());
  return out;
}

const longListDone = new Set<string>();

type Edit = { label: string; apply: (e: IrExpr) => void; applies: (e: IrExpr) => boolean };

const OTHER: Record<string, TypeName> = { bool: 'int32', utf8: 'int32' };

function exprEdits(): Edit[] {
  // Purpose: changes to one expression that a validator should catch (or, for some, should not mind)
  const any = (e: IrExpr): Record<string, unknown> => e as unknown as Record<string, unknown>;
  const retype = (e: IrExpr): void => void (any(e).type = { name: OTHER[e.type.name] ?? 'bool' });
  return [
    { label: 'retype', applies: () => true, apply: retype },
    { label: 'field-out-of-range', applies: e => e.kind === 'field', apply: e => void (any(e).index = 99) },
    { label: 'field-type', applies: e => e.kind === 'field', apply: retype },
    { label: 'unknown-fn', applies: e => e.kind === 'call', apply: e => void (any(e).fn = 'no_such_fn') },
    { label: 'aggregate-as-scalar', applies: e => e.kind === 'call', apply: e => void (any(e).fn = 'sum') },
    { label: 'drop-arg', applies: e => e.kind === 'call', apply: e => void (any(e).args as IrExpr[]).pop() },
    { label: 'extra-arg', applies: e => e.kind === 'call', apply: e => void (any(e).args as IrExpr[]).push((any(e).args as IrExpr[])[0]!) },
    { label: 'swap-fn', applies: e => e.kind === 'call', apply: e => void (any(e).fn = any(e).fn === 'and' ? 'or' : any(e).fn === 'eq' ? 'lt' : 'add') },
    { label: 'cast-to-string', applies: e => e.kind === 'cast', apply: e => void (any(e).type = { name: 'utf8' }) },
    { label: 'cast-from-string', applies: e => e.kind === 'cast', apply: e => void (any((any(e).arg as IrExpr)).type = { name: 'utf8' }) },
    { label: 'param-undeclared', applies: e => e.kind === 'param', apply: e => void (any(e).name = 'nope') },
    { label: 'in-param-undeclared', applies: e => e.kind === 'in' && e.param !== null, apply: e => void (any(e).param = 'nope') },
    { label: 'in-not-bool', applies: e => e.kind === 'in', apply: e => void (any(e).type = { name: 'int32' }) },
    // One copy of this one is enough: it is 200 KB of bytes. Single-byte literals keep it small.
    { label: 'in-too-long', applies: e => e.kind === 'in' && e.values !== null && !longListDone.has('x'), apply: e => { longListDone.add('x'); any(e).values = new Array<boolean>(65537).fill(true); } },
    { label: 'literal-retype', applies: e => e.kind === 'literal', apply: retype },
  ];
}

function mutants(base: { name: string; plan: IrPlan }): { name: string; plan: IrPlan }[] {
  // Purpose: every single change in the edit list applied to every place it fits in a plan, plus plan-level and node-level breakage
  const out: { name: string; plan: IrPlan }[] = [{ name: `${base.name}:original`, plan: base.plan }];
  const clone = (): IrPlan => structuredClone(base.plan);
  const total = base.plan.nodes.reduce((n, node) => n + nodeExprs(node).reduce((m, e) => { let c = 0; walkExpr(e, () => c++); return m + c; }, 0), 0);
  for (const edit of exprEdits()) {
    let applied = 0;
    for (let target = 0; target < total && applied < 4; target++) {
      const copy = clone();
      let at = 0;
      let done = false;
      for (const node of copy.nodes) {
        for (const root of nodeExprs(node)) {
          walkExpr(root, e => {
            if (at++ === target && edit.applies(e)) {
              edit.apply(e);
              done = true;
            }
          });
        }
      }
      if (done) {
        applied++;
        out.push({ name: `${base.name}:${edit.label}@${target}`, plan: copy });
      }
    }
  }
  const nodeEdits: [string, (p: IrPlan) => void][] = [
    ['root-out-of-range', p => void ((p as unknown as { root: number }).root = p.nodes.length)],
    ['root-first', p => void ((p as unknown as { root: number }).root = 0)],
    ['extra-scan', p => void (p.nodes as unknown as unknown[]).push({ op: 'scan', schema: p.input })],
    ['dup-param', p => { if (p.params.length > 0) (p.params as unknown as unknown[]).push(p.params[0]); }],
    ['flip-param-list', p => { for (const param of p.params) (param as { list: boolean }).list = !param.list; }],
    ['no-params', p => void ((p as unknown as { params: unknown[] }).params = [])],
    ['no-nodes', p => void ((p as unknown as { nodes: unknown[] }).nodes = [])],
    ['first-not-scan', p => void ((p.nodes as unknown as unknown[])[0] = { ...(p.nodes[0] as object), op: 'limit', input: 0, count: 1 })],
  ];
  for (const [label, edit] of nodeEdits) {
    const copy = clone();
    edit(copy);
    out.push({ name: `${base.name}:${label}`, plan: copy });
  }
  for (let i = 1; i < base.plan.nodes.length; i++) {
    for (const [label, edit] of [
      ['input-self', (n: Record<string, unknown>) => void (n.input = i)],
      // A filter whose predicate is a real, correctly typed column that is not bool: only the predicate rule objects.
      ['predicate-column', (n: Record<string, unknown>, p: IrPlan) => {
        if (n.op !== 'filter') return;
        const schema = p.nodes[n.input as number]!.schema;
        const index = schema.findIndex(f => f.type.name !== 'bool');
        n.predicate = { kind: 'field', index, type: schema[index]!.type };
      }],
      ['input-later', (n: Record<string, unknown>) => void (n.input = i + 1)],
      ['schema-longer', (n: Record<string, unknown>) => void (n.schema = [...(n.schema as unknown[]), { name: 'x', type: t.bool }])],
      ['predicate-int', (n: Record<string, unknown>) => { if (n.predicate) (n.predicate as { type: unknown }).type = t.int32; }],
      ['agg-unknown', (n: Record<string, unknown>) => { if (n.aggs) ((n.aggs as { fn: string }[])[0]!).fn = 'nope'; }],
      ['agg-scalar', (n: Record<string, unknown>) => { if (n.aggs) ((n.aggs as { fn: string }[])[0]!).fn = 'add'; }],
      ['sort-bool', (n: Record<string, unknown>) => { if (n.keys && n.op === 'sort') ((n.keys as { expr: { type: unknown } }[])[0]!).expr.type = t.bool; }],
      // The People schema's `ok` column (index 7) is a real bool, so only the sort rule objects.
      ['sort-bool-column', (n: Record<string, unknown>) => { if (n.keys && n.op === 'sort') ((n.keys as { expr: unknown }[])[0]!).expr = { kind: 'field', index: 7, type: t.bool }; }],
    ] as [string, (n: Record<string, unknown>, p: IrPlan) => void][]) {
      const copy = clone();
      edit(copy.nodes[i] as unknown as Record<string, unknown>, copy);
      out.push({ name: `${base.name}:node${i}-${label}`, plan: copy });
    }
  }
  return out;
}

function hex(bytes: Uint8Array): string {
  // Purpose: bytes as lower-case hex
  return Array.from(bytes, b => b.toString(16).padStart(2, '0')).join('');
}

function verdict(bytes: Uint8Array): 'ok' | 'invalid' {
  // Purpose: the JS decoder and validator's verdict on some bytes
  try {
    validate(decodePlan(bytes));
    return 'ok';
  } catch (error) {
    if (error instanceof PlanError) return 'invalid';
    throw error;
  }
}

function limitForms(): [string, Uint8Array][] {
  // Purpose: a plan with a limit of 77777 (varint d1 df 04), rewritten into counts at and beyond the largest safe integer
  const plan = pipe(People).limit(77777).compile().ir;
  const bytes = encodePlan(plan);
  let at = -1;
  for (let i = 0; i + 2 < bytes.length; i++) if (bytes[i] === 0xd1 && bytes[i + 1] === 0xdf && bytes[i + 2] === 0x04) at = i;
  if (at < 0) throw new Error('limit marker not found');
  const forms: [string, number[]][] = [
    ['77777', [0xd1, 0xa5, 0x04]],
    ['2^53-1', [0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x0f]],
    ['2^53', [0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x10]],
    ['2^56-1', [0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x7f]],
    ['nine-byte-varint', [0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x01]],
    ['zero-in-two-bytes', [0x80, 0x00]],
  ];
  return forms.map(([name, v]) => [name, new Uint8Array([...bytes.subarray(0, at), ...v, ...bytes.subarray(at + 3)])]);
}

function literalForms(): [string, Uint8Array][] {
  // Purpose: one plan with a single literal, rewritten byte by byte into every literal form, canonical or not
  const field = { name: 'x', type: t.float64 };
  const plan: IrPlan = {
    version: IR_VERSION,
    input: [field],
    nodes: [
      { op: 'scan', schema: [field] },
      { op: 'project', input: 0, exprs: [{ kind: 'literal', value: 7, type: t.float64 }], schema: [field] },
    ],
    root: 1,
    output: [field],
    params: [],
  };
  const bytes = encodePlan(plan);
  // The expression is: kind 1 (literal), type 10 (float64), then the literal: tag 2 (int) and zigzag(7) = 14.
  let at = -1;
  for (let i = 0; i + 3 < bytes.length; i++) if (bytes[i] === 1 && bytes[i + 1] === 10 && bytes[i + 2] === 2 && bytes[i + 3] === 14) at = i + 2;
  if (at < 0) throw new Error('literal marker not found');
  const f64 = (v: number): number[] => Array.from(new Uint8Array(new Float64Array([v]).buffer));
  const bits = (hi: number): number[] => [0, 0, 0, 0, 0, 0, hi & 255, hi >> 8];
  const u64 = (v: bigint): number[] => Array.from(new Uint8Array(new BigUint64Array([v]).buffer));
  const forms: [string, number[]][] = [
    ['int-7', [2, 14]],
    ['float-7.0 (must be an int)', [3, ...f64(7)]],
    ['float-7.5', [3, ...f64(7.5)]],
    ['float-minus-zero', [3, ...f64(-0)]],
    ['float-2^52-1 (must be an int)', [3, ...f64(2 ** 52 - 1)]],
    ['float-2^52', [3, ...f64(2 ** 52)]],
    ['float-infinity', [3, ...f64(Infinity)]],
    ['nan-standard', [3, ...f64(NaN)]],
    ['nan-other-payload', [3, ...bits(0x7ff9)]],
    ['nan-negative', [3, ...bits(0xfff8)]],
    ['int-largest', [2, 0xfe, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x0f]],
    ['int-too-large', [2, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x0f]],
    ['big-zero', [4, ...u64(0n)]],
    ['big-max', [4, ...u64(2n ** 64n - 1n)]],
    ['big-negative', [5, ...u64(5n)]],
    ['big-negative-zero', [5, ...u64(0n)]],
    ['string-empty', [6, 0]],
    ['string-bom', [6, 3, 0xef, 0xbb, 0xbf]],
    ['string-invalid-utf8', [6, 1, 0xff]],
    ['string-surrogate', [6, 3, 0xed, 0xa0, 0x80]],
    ['string-overlong', [6, 2, 0xc0, 0x80]],
    ['unknown-tag', [7]],
    ['truncated-float', [3, 1, 2, 3]],
  ];
  return forms.map(([name, lit]) => [name, new Uint8Array([...bytes.subarray(0, at), ...lit, ...bytes.subarray(at + 2)])]);
}

export function corpusText(): string {
  // Purpose: the corpus, one line per plan: name, verdict, bytes in hex; also truncated and corrupted byte strings that must not decode
  const seen = new Set<string>();
  const lines: string[] = ['# name<TAB>verdict<TAB>hex. Generated by `bun run gen:engine`; the verdict is the JS decoder and validator\'s.'];
  const push = (name: string, bytes: Uint8Array): void => {
    // Purpose: add one entry unless an identical byte string is already there
    const h = hex(bytes);
    if (seen.has(h)) return;
    seen.add(h);
    lines.push(`${name}\t${verdict(bytes)}\t${h}`);
  };
  for (const base of basePlans()) {
    for (const m of mutants(base)) {
      let bytes: Uint8Array;
      try {
        bytes = encodePlan(m.plan);
      } catch (error) {
        if (error instanceof PlanError) continue; // cannot even be written
        throw error;
      }
      push(m.name, bytes);
    }
  }
  for (const [name, bytes] of literalForms()) push(`literal:${name}`, bytes);
  for (const [name, bytes] of limitForms()) push(`limit:${name}`, bytes);
  const sample = encodePlan(basePlans()[0]!.plan);
  for (let n = 0; n < sample.length; n += 3) push(`truncated@${n}`, sample.subarray(0, n));
  let seed = 7;
  const next = (): number => {
    seed = (Math.imul(seed, 1103515245) + 12345) >>> 0;
    return seed >>> 16;
  };
  for (let i = 0; i < 300; i++) {
    const copy = sample.slice();
    copy[next() % copy.length] ^= 1 << (next() % 8);
    push(`bitflip#${i}`, copy);
  }
  void IR_VERSION;
  return `${lines.join('\n')}\n`;
}

